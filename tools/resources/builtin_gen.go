//go:build ignore

// builtin_gen.go compiles the built-in high-risk command corpus
// (guardrail_builtin.yaml) into a Go file the guardrail runtime embeds. Fork
// patch 23b (docs/04): the guaranteed audit corpus must always ship in the
// binary — unlike the templates bundle it carries no build tag, because the
// scan-capture recipe strips the template resources but never the audit duty.
//
// Patterns are compiled at generation time: an invalid regex fails here, not
// on the proxy data path.
//
//	go:generate go run ./builtin_gen.go -t guardrail_builtin.yaml -o guardrail_builtin_gen.go
package main

import (
	"flag"
	"fmt"
	"os"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
)

type corpus struct {
	Patterns []struct {
		ID      string `yaml:"id"`
		Pattern string `yaml:"pattern"`
		Desc    string `yaml:"desc"`
	} `yaml:"patterns"`
}

func main() {
	src := flag.String("t", "guardrail_builtin.yaml", "corpus YAML")
	out := flag.String("o", "guardrail_builtin_gen.go", "output Go file")
	flag.Parse()

	raw, err := os.ReadFile(*src)
	if err != nil {
		fmt.Fprintf(os.Stderr, "read %s: %v\n", *src, err)
		os.Exit(1)
	}
	var c corpus
	if err := yaml.Unmarshal(raw, &c); err != nil {
		fmt.Fprintf(os.Stderr, "parse %s: %v\n", *src, err)
		os.Exit(1)
	}
	if len(c.Patterns) == 0 {
		fmt.Fprintf(os.Stderr, "%s defines no patterns\n", *src)
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by builtin_gen.go from guardrail_builtin.yaml; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// The built-in high-risk command corpus (fork patch 23b): the guaranteed\n")
	b.WriteString("// audit patterns, compiled at generation time. No build tag — the corpus\n")
	b.WriteString("// ships in every binary form, including the resource-stripped\n")
	b.WriteString("// scan-capture recipe.\n\n")
	b.WriteString("package resources\n\n")
	b.WriteString("import \"regexp\"\n\n")
	b.WriteString("// BuiltinPattern is one guaranteed-audit command pattern.\ntype BuiltinPattern struct {\n\tID      string\n\tPattern *regexp.Regexp\n\tDesc    string\n}\n\n")
	b.WriteString("// GuardrailBuiltinPatterns is the corpus the guardrail runtime audits\n")
	b.WriteString("// unconditionally (reason prefix \"builtin.\").\nvar GuardrailBuiltinPatterns = []BuiltinPattern{\n")
	for _, p := range c.Patterns {
		if _, err := regexp.Compile(p.Pattern); err != nil {
			fmt.Fprintf(os.Stderr, "pattern %s does not compile: %v\n", p.ID, err)
			os.Exit(1)
		}
		b.WriteString(fmt.Sprintf("\t{ID: %q, Pattern: regexp.MustCompile(%q), Desc: %q},\n", p.ID, p.Pattern, p.Desc))
	}
	b.WriteString("}\n")

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write %s: %v\n", *out, err)
		os.Exit(1)
	}
	fmt.Printf("builtin_gen: %d patterns -> %s\n", len(c.Patterns), *out)
}
